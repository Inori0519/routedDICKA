"""Export deterministic LaTeX tables for the Supplementary Information."""

from __future__ import annotations

import argparse
from fractions import Fraction
from hashlib import sha256
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUTCOME_TEX = {0: "+", 1: "-", 2: r"\perp"}
WORD_NAMES = {
    (): r"\id",
    (0,): r"A_Z^+",
    (1,): r"A_X^+",
    (2,): r"S_0^+",
    (3,): r"S_1^+",
    (4,): r"L_+",
    (5,): r"L_-",
    (0, 2): r"A_Z^+S_0^+",
    (0, 3): r"A_Z^+S_1^+",
    (0, 4): r"A_Z^+L_+",
    (0, 5): r"A_Z^+L_-",
    (1, 2): r"A_X^+S_0^+",
    (1, 3): r"A_X^+S_1^+",
    (1, 4): r"A_X^+L_+",
    (1, 5): r"A_X^+L_-",
}


def _read_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def _fraction_tex(value: str) -> str:
    rational = Fraction(value)
    numerator, denominator = rational.numerator, rational.denominator
    if denominator == 1:
        return str(numerator)
    if denominator & (denominator - 1) == 0:
        return rf"{numerator}\,2^{{-{denominator.bit_length() - 1}}}"
    return f"{numerator}/{denominator}"


def _response_tex(response: list[int]) -> str:
    return "$({})$".format(",".join(OUTCOME_TEX[value] for value in response))


def _hash(path: Path) -> str:
    return sha256(path.read_bytes()).hexdigest()


def _split_hash(value: str) -> str:
    return rf"\texttt{{{value[:32]}}}\newline\texttt{{{value[32:]}}}"


def export_attack_table(root: Path, output: Path) -> None:
    payload = _read_json(root / "source_data" / "attack" / "attack_eta078.json")
    strategies = payload["local_strategies"]
    weights = payload["local_weights"]
    if len(strategies) != 123 or len(weights) != 123:
        raise ValueError("The frozen attack must contain exactly 123 local atoms")

    lines = [
        "% Generated by main/export_supplement_tables.py; do not edit by hand.",
        r"\begin{longtable}{rccc>{\raggedleft\arraybackslash}p{0.25\linewidth}>{\raggedleft\arraybackslash}p{0.25\linewidth}}",
        r"\caption{Complete deterministic part of the exact remote attack. Input orders are $(Z,X)$ for Alice, $(Z,X,T_0,T_1)$ for Bob and $(Z,X)$ for Charlie. Outcomes $0,1,2$ in the electronic data are displayed as $+,-,\perp$. Each exact weight is $w_j=a_j+b_jr$, where $r=50/\sqrt{4021}$. Coefficients use single-line ratios or $n\,2^{-k}$, without decimal rounding.}\label{tab:attack-atoms}\\",
        r"\toprule",
        r"$j$ & Alice & Bob & Charlie & $a_j$ & $b_j$\\",
        r"\midrule",
        r"\endfirsthead",
        r"\multicolumn{6}{c}{\tablename\ \thetable\ (continued)}\\",
        r"\toprule",
        r"$j$ & Alice & Bob & Charlie & $a_j$ & $b_j$\\",
        r"\midrule",
        r"\endhead",
        r"\midrule\multicolumn{6}{r}{Continued on next page}\\",
        r"\endfoot",
        r"\bottomrule",
        r"\endlastfoot",
    ]
    for index, (strategy, weight) in enumerate(zip(strategies, weights), start=1):
        alice, bob, charlie = strategy
        lines.append(
            "{} & {} & {} & {} & ${}$ & ${}$\\\\".format(
                index,
                _response_tex(alice),
                _response_tex(bob),
                _response_tex(charlie),
                _fraction_tex(weight[0]),
                _fraction_tex(weight[1]),
            )
        )
    lines.append(r"\end{longtable}")
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")


def export_affine_table(source: Path, output: Path, caption: str, label: str) -> None:
    payload = _read_json(source)
    node_index = payload.get("metadata", {}).get("node_index")
    node_label = str(node_index + 1) if node_index is not None else "ref."
    lines = [
        "% Generated by main/export_supplement_tables.py; do not edit by hand.",
        r"\begin{longtable}{clp{0.58\linewidth}}",
        rf"\caption{{{caption}}}\label{{{label}}}\\",
        r"\toprule",
        r"Node & Moment & Exact affine coefficient\\",
        r"\midrule",
        r"\endfirsthead",
        r"\multicolumn{3}{c}{\tablename\ \thetable\ (continued)}\\",
        r"\toprule",
        r"Node & Moment & Exact affine coefficient\\",
        r"\midrule",
        r"\endhead",
        r"\bottomrule",
        r"\endlastfoot",
    ]
    for coefficient in payload["coefficients"]:
        word = tuple(coefficient["word"])
        try:
            moment = WORD_NAMES[word]
        except KeyError as error:
            raise ValueError(f"Unknown affine word {word} in {source}") from error
        lines.append(
            rf"{node_label} & ${moment}$ & ${_fraction_tex(coefficient['value'])}$\\"
        )
    lines.extend(
        [
            r"\midrule",
            rf"{node_label} & residual deduction & ${_fraction_tex(payload['residual_penalty'])}$\\",
            r"\end{longtable}",
        ]
    )
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")


def export_m4_affine_table(root: Path, output: Path) -> None:
    sources = sorted((root / "source_data" / "certificates" / "m4").glob("node_*.affine.json"))
    if len(sources) != 3:
        raise ValueError("The frozen m=4 certificate must contain three affine nodes")
    lines = [
        "% Generated by main/export_supplement_tables.py; do not edit by hand.",
        r"\begin{longtable}{clp{0.58\linewidth}}",
        r"\caption{Exact affine coefficients of the three-node $m=4$ entropy certificate. Dyadic values are written as $n\,2^{-k}$ and other rationals as single-line ratios. The residual deduction after each node is subtracted from that node bound.}\label{tab:m4-affine}\\",
        r"\toprule",
        r"Node & Moment & Exact affine coefficient\\",
        r"\midrule",
        r"\endfirsthead",
        r"\multicolumn{3}{c}{\tablename\ \thetable\ (continued)}\\",
        r"\toprule",
        r"Node & Moment & Exact affine coefficient\\",
        r"\midrule",
        r"\endhead",
        r"\bottomrule",
        r"\endlastfoot",
    ]
    for source in sources:
        payload = _read_json(source)
        node = payload["metadata"]["node_index"] + 1
        for coefficient in payload["coefficients"]:
            word = tuple(coefficient["word"])
            try:
                moment = WORD_NAMES[word]
            except KeyError as error:
                raise ValueError(f"Unknown affine word {word} in {source}") from error
            lines.append(
                rf"{node} & ${moment}$ & ${_fraction_tex(coefficient['value'])}$\\"
            )
        lines.append(
            rf"{node} & residual deduction & ${_fraction_tex(payload['residual_penalty'])}$\\"
        )
        if source != sources[-1]:
            lines.append(r"\midrule")
    lines.append(r"\end{longtable}")
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")


def export_manifest(root: Path, latex_output: Path, json_output: Path) -> None:
    source_root = root / "source_data"
    files = sorted(path for path in source_root.rglob("*.json") if path.is_file())
    manifest = {
        "schema": "routed-dicka-frozen-proof-objects-v1",
        "files": [
            {
                "path": path.relative_to(root).as_posix(),
                "bytes": path.stat().st_size,
                "sha256": _hash(path),
            }
            for path in files
        ],
    }
    json_output.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

    lines = [
        "% Generated by main/export_supplement_tables.py; do not edit by hand.",
        r"\begin{longtable}{p{0.38\linewidth}rp{0.46\linewidth}}",
        r"\caption{Frozen machine-readable proof objects. Hashes are SHA-256 digests of the files distributed with this manuscript.}\label{tab:proof-manifest}\\",
        r"\toprule",
        r"Relative path & Bytes & SHA-256\\",
        r"\midrule",
        r"\endfirsthead",
        r"\multicolumn{3}{c}{\tablename\ \thetable\ (continued)}\\",
        r"\toprule",
        r"Relative path & Bytes & SHA-256\\",
        r"\midrule",
        r"\endhead",
        r"\bottomrule",
        r"\endlastfoot",
    ]
    for item in manifest["files"]:
        path_tex = item["path"].replace("_", r"\_")
        lines.append(
            rf"\texttt{{{path_tex}}} & {item['bytes']} & {_split_hash(item['sha256'])}\\"
        )
    lines.append(r"\end{longtable}")
    latex_output.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    args = parser.parse_args()
    root = args.root.resolve()
    generated = root / "paper" / "generated"
    generated.mkdir(parents=True, exist_ok=True)

    export_attack_table(root, generated / "attack_weights_table.tex")
    export_affine_table(
        root / "source_data" / "certificates" / "archived_m2" / "near_m2.affine.json",
        generated / "archived_m2_affine_table.tex",
        "Exact coefficients of the independently checked $m=2$ near--phase affine certificate, written as $n\\,2^{-k}$ or single-line ratios.",
        "tab:archived-m2-affine",
    )
    export_m4_affine_table(root, generated / "m4_affine_table.tex")
    export_manifest(
        root,
        generated / "proof_manifest_table.tex",
        generated / "proof_manifest.json",
    )
    print(f"Supplement tables written to {generated}")


if __name__ == "__main__":
    main()
